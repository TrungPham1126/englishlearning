import React, { forwardRef } from "react";
import { cn } from "@/lib/utils";

export const Card = forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-slate-200 dark:border-slate-800/80 bg-white dark:bg-[#0e1526] text-slate-900 dark:text-slate-100 shadow-card transition-all duration-200",
      hoverable && "hover:border-slate-300 dark:hover:border-slate-700 hover:shadow-card-hover",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

